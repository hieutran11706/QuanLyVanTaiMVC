WHERE NOT EXISTS (SELECT 1 FROM TINHTHANH WHERE TEN_TINH = 'Can Tho');

INSERT INTO TINHTHANH (TEN_TINH, MA_VUNG)
SELECT 'Hai Phong', 'MB' FROM DUAL
WHERE NOT EXISTS (SELECT 1 FROM TINHTHANH WHERE TEN_TINH = 'Hai Phong');

COMMIT;

